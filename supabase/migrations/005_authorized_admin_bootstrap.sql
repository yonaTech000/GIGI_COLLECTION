-- Local bootstrap template for two authorised admin accounts.
-- This file is intentionally not part of the normal migration sequence and must be executed
-- only in the target Supabase project after the Auth users already exist.
--
-- Replace the placeholders below with the actual administrator email addresses used in the
-- target Supabase project. Do not commit real credentials or passwords into source control.
--
-- Example placeholders:
--   developer_email: developer@example.com
--   owner_email: owner@example.com
--   developer_username: developer
--   owner_username: owner
--
-- The app login flow accepts username or phone number in the public auth form, then looks
-- up the matching profile and signs in through Supabase Auth. The trusted database-side role
-- assignment remains enforced by public.assign_authorized_role(...), never by browser state.

-- 1) Create or confirm the Auth users in Supabase Authentication > Users.
--    Make sure each user has a matching row in public.profiles, generated by the trigger in
--    001_initial_schema.sql.
--
-- 2) Assign the database-authoritative roles after the profile rows exist.
select public.assign_authorized_role(
  (select id from public.profiles where email = 'developer@example.com'),
  'developer'
);

select public.assign_authorized_role(
  (select id from public.profiles where email = 'owner@example.com'),
  'owner'
);

-- 3) Verify the final authorized state.
select *
from public.profiles
where email in ('developer@example.com', 'owner@example.com')
order by role, email;

select * from public.authorized_account_status();

